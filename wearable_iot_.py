from pathlib import Path
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline
from sklearn.ensemble import RandomForestClassifier, IsolationForest
from sklearn.metrics import classification_report, ConfusionMatrixDisplay, accuracy_score

# Define paths using the provided absolute dataset path
DATA_PATH = Path("/wearable_iot_health_dataset.csv")
HERE = DATA_PATH.parent
OUT = HERE / "outputs"
OUT.mkdir(exist_ok=True)

df = pd.read_csv(DATA_PATH, parse_dates=["timestamp"])

print("Original shape:", df.shape)
print("Missing values:\n", df.isna().sum())
print("Duplicate rows:", df.duplicated().sum())

# Clean duplicate ingestion records and derive time features
df = df.drop_duplicates().sort_values("timestamp").reset_index(drop=True)
df["hour"] = df.timestamp.dt.hour
df["day_of_week"] = df.timestamp.dt.dayofweek

# Visualisation 1: heart-rate distribution
df.heart_rate_bpm.hist(bins=35, figsize=(8,5))
plt.title("Heart Rate Distribution"); plt.xlabel("Heart rate (BPM)"); plt.ylabel("Readings")
plt.tight_layout(); plt.savefig(OUT/"01_heart_rate_distribution.png"); plt.close()

# Visualisation 2: relationship between two physiological measurements
plt.figure(figsize=(8,5))
plt.scatter(df.heart_rate_bpm, df.spo2_percent, alpha=.35)
plt.xlabel("Heart rate (BPM)"); plt.ylabel("SpO2 (%)")
plt.title("Heart Rate vs SpO2"); plt.tight_layout()
plt.savefig(OUT/"02_heart_rate_vs_spo2.png"); plt.close()

# Visualisation 3: correlation matrix
num_cols = ["heart_rate_bpm","spo2_percent","skin_temperature_c","step_count_15min",
            "battery_percent","signal_strength_dbm","network_latency_ms",
            "packet_loss_percent","sensor_quality_score","hour","day_of_week","review_flag"]
corr = df[num_cols].corr()
plt.figure(figsize=(11,8)); plt.imshow(corr, aspect="auto", vmin=-1, vmax=1)
plt.colorbar(label="Correlation")
plt.xticks(range(len(num_cols)),num_cols,rotation=70,ha="right")
plt.yticks(range(len(num_cols)),num_cols); plt.title("IoT Feature Correlation Matrix")
plt.tight_layout(); plt.savefig(OUT/"03_correlation_matrix.png"); plt.close()

# Visualisation 4: average readings by activity
df.groupby("activity")[["heart_rate_bpm","spo2_percent","step_count_15min"]].mean().plot(kind="bar",figsize=(9,5))
plt.title("Average Sensor Readings by Activity"); plt.ylabel("Average (different units)")
plt.tight_layout(); plt.savefig(OUT/"04_activity_comparison.png"); plt.close()

# IQR outlier flags: flag potential outliers; do not automatically delete valid extremes
for c in ["heart_rate_bpm","spo2_percent","skin_temperature_c","network_latency_ms"]:
    q1,q3=df[c].quantile([.25,.75]); iqr=q3-q1
    df[c+"_outlier_iqr"]=((df[c]<q1-1.5*iqr)|(df[c]>q3+1.5*iqr)).astype(int)

# Supervised learning. The target is a synthetic rule-based review flag, not a diagnosis.
numeric = ["heart_rate_bpm","spo2_percent","skin_temperature_c","step_count_15min",
           "battery_percent","signal_strength_dbm","network_latency_ms",
           "packet_loss_percent","sensor_quality_score","hour","day_of_week"]
categorical = ["activity"]
X=df[numeric+categorical]; y=df["review_flag"]
prep=ColumnTransformer([
    ("numeric",Pipeline([("imputer",SimpleImputer(strategy="median")),("scale",StandardScaler())]),numeric),
    ("category",Pipeline([("imputer",SimpleImputer(strategy="most_frequent")),
                          ("encode",OneHotEncoder(handle_unknown="ignore"))]),categorical)
])
model=Pipeline([("preprocess",prep),("rf",RandomForestClassifier(
    n_estimators=200,max_depth=10,class_weight="balanced",random_state=42))])
Xtr,Xte,ytr,yte=train_test_split(X,y,test_size=.2,random_state=42,stratify=y)
model.fit(Xtr,ytr); pred=model.predict(Xte)
print("Accuracy:",round(accuracy_score(yte,pred),3))
print(classification_report(yte,pred,zero_division=0))
ConfusionMatrixDisplay.from_predictions(yte,pred)
plt.title("Review Flag - Confusion Matrix"); plt.tight_layout()
plt.savefig(OUT/"05_confusion_matrix.png"); plt.close()

# Unsupervised anomaly detection on sensor + device telemetry
iso_cols=["heart_rate_bpm","spo2_percent","skin_temperature_c","step_count_15min",
          "network_latency_ms","packet_loss_percent","sensor_quality_score"]
iso_data=df[iso_cols].fillna(df[iso_cols].median())
iso=IsolationForest(contamination=.04,random_state=42)
df["isolation_forest_anomaly"]=(iso.fit_predict(iso_data)==-1).astype(int)

df.to_csv(OUT/"cleaned_wearable_iot_dataset.csv",index=False)
df.groupby("activity").agg(readings=("activity","size"),
    avg_heart_rate=("heart_rate_bpm","mean"),avg_spo2=("spo2_percent","mean"),
    avg_steps=("step_count_15min","mean"),review_flag_rate=("review_flag","mean")
).round(2).to_csv(OUT/"activity_summary.csv")
print("Completed. See outputs folder:",OUT)

