import panel as pn
import plotly.express as px
pn.extension('plotly')

# Create a patient selector dropdown
patient_ids = sorted(df['patient_id'].unique().tolist())
patient_select = pn.widgets.Select(name='Select Patient ID', options=patient_ids, value=patient_ids[0])

# Define a reactive function that updates the plots based on selected patient
@pn.depends(patient_select.param.value)
def get_patient_plots(selected_patient):
    patient_df = df[df['patient_id'] == selected_patient].sort_values('timestamp')

    # Plot 1: Heart Rate Over Time
    fig_hr = px.line(
        patient_df,
        x='timestamp',
        y='heart_rate_bpm',
        color='activity',
        title=f"Heart Rate Monitoring Over Time (Patient {selected_patient})",
        labels={'heart_rate_bpm': 'Heart Rate (BPM)', 'timestamp': 'Time'}
    )

    # Plot 2: SpO2 Over Time
    fig_spo2 = px.line(
        patient_df,
        x='timestamp',
        y='spo2_percent',
        title=f"SpO₂ Level Over Time (Patient {selected_patient})",
        labels={'spo2_percent': 'SpO₂ (%)', 'timestamp': 'Time'}
    )

    # Plot 3: Skin Temperature Over Time
    fig_temp = px.line(
        patient_df,
        x='timestamp',
        y='skin_temperature_c',
        title=f"Skin Temperature Over Time (Patient {selected_patient})",
        labels={'skin_temperature_c': 'Skin Temp (°C)', 'timestamp': 'Time'}
    )

    # Calculate key stats
    avg_hr = round(patient_df['heart_rate_bpm'].mean(), 1)
    avg_spo2 = round(patient_df['spo2_percent'].mean(), 1)
    avg_temp = round(patient_df['skin_temperature_c'].mean(), 1)

    stats_markdown = pn.pane.Markdown(f"""
    ### Patient Metrics Summary:
    * **Average Heart Rate:** {avg_hr} BPM
    * **Average SpO₂:** {avg_spo2} %
    * **Average Skin Temperature:** {avg_temp} °C
    """)

    return pn.Column(
        stats_markdown,
        pn.Row(fig_hr, fig_spo2),
        pn.Row(fig_temp)
    )

# Build and display the patient-wise dashboard layout
patient_dashboard = pn.Column(
    "## Patient-Wise Interactive Telemetry Monitoring",
    patient_select,
    get_patient_plots
)

patient_dashboard.servable()